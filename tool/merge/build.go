package merge

import (
	"cmp"
	"go/ast"
	"go/scanner"
	"go/token"
	"maps"
	"slices"

	"github.com/goplus/llcppg/tool"
)

// build lays out the merged files. Shared declarations keep their source file name,
// and the rest of each platform goes to a constrained file such as z_linux_amd64.go.
func (p *mergeIndex) build(pkgName string) map[string]*ast.File {
	decls := p.buildShared()
	constraints := make(map[string]string) // file name => build constraint
	for platform, pkg := range p.files.pkgs {
		if list := p.buildPlatform(platform); len(list) != 0 {
			name := "z_" + pkg.Tags[0] + "_" + pkg.Tags[1] + ".go"
			decls[name] = list
			constraints[name] = "//go:build " + pkg.Tags[0] + " && " + pkg.Tags[1]
		}
	}
	header := generatedHeader()
	files := make(map[string]*ast.File, len(decls))
	for name, list := range decls {
		files[name] = p.buildFile(pkgName, list, header, constraints[name])
	}
	return files
}

// buildPlatform returns the declarations of a platform that are not shared,
// with the source files in name order.
func (p *mergeIndex) buildPlatform(platform int) []ast.Decl {
	files := p.files.pkgs[platform].Files
	var decls []ast.Decl
	for _, name := range slices.Sorted(maps.Keys(files)) {
		file := files[name]
		list := filter(file, func(declIndex, specIndex int) bool {
			if decl, ok := file.Decls[declIndex].(*ast.GenDecl); ok && decl.Tok == token.IMPORT {
				return false
			}
			return !p.replaced(declRef{platform: platform, file: name, declIndex: declIndex, specIndex: specIndex})
		})
		sortDecls(file, list)
		decls = append(decls, list...)
	}
	return decls
}

// replaced reports whether a shared group replaces the declaration at ref.
// It looks the group up in the index rather than keeping a set of replaced refs.
func (p *mergeIndex) replaced(ref declRef) bool {
	switch decl := p.files.decl(ref).(type) {
	case *ast.FuncDecl:
		for _, refs := range p.symbols[funcKey(decl)] {
			if p.shared(refs) && slices.Contains(refs, ref) {
				return true
			}
		}
	case *ast.GenDecl:
		switch decl.Tok {
		case token.TYPE:
			refs, ok := p.types.at(decl.Specs[ref.specIndex]).(*[]declRef)
			return ok && p.shared(*refs) && slices.Contains(*refs, ref)
		case token.VAR, token.CONST:
			names := decl.Specs[ref.specIndex].(*ast.ValueSpec).Names
			if len(names) != 0 {
				refs := p.values[names[0].Name]
				return p.shared(refs) && slices.Contains(refs, ref)
			}
		}
	}
	return false
}

func (p *mergeIndex) buildFile(pkgName string, decls []ast.Decl, header []string, constraint string) *ast.File {
	file := &ast.File{Name: ast.NewIdent(pkgName), Decls: decls}
	p.buildImports(file)
	var doc []*ast.Comment
	if constraint != "" {
		// The printer separates //go:build linux && amd64 from the package clause.
		doc = append(doc, &ast.Comment{Text: constraint})
	}
	for _, text := range header {
		doc = append(doc, &ast.Comment{Text: text})
	}
	if len(doc) != 0 {
		file.Doc = &ast.CommentGroup{List: doc}
	}
	return file
}

// generatedHeader splits tool.GeneratedHeader into comments, such as
// "// Code generated by llcppg; DO NOT EDIT.".
func generatedHeader() []string {
	src := []byte(tool.GeneratedHeader)
	if len(src) == 0 {
		return nil
	}
	var scan scanner.Scanner
	scan.Init(token.NewFileSet().AddFile("", -1, len(src)), src, nil, scanner.ScanComments)
	var comments []string
	for _, tok, text := scan.Scan(); tok == token.COMMENT; _, tok, text = scan.Scan() {
		comments = append(comments, text)
	}
	return comments
}

// sortDecls orders decls by source position.
// It keeps input order when a file lacks positions, as with gogen's ASTFile.
func sortDecls(file *ast.File, decls []ast.Decl) {
	if !hasPositions(file) {
		return
	}
	for _, decl := range decls {
		if decl, ok := valueOrTypeDecl(decl); ok {
			slices.SortStableFunc(decl.Specs, func(a, b ast.Spec) int {
				return cmp.Compare(a.Pos(), b.Pos())
			})
		}
	}
	position := func(decl ast.Decl) token.Pos {
		if decl, ok := valueOrTypeDecl(decl); ok {
			return decl.Specs[0].Pos()
		}
		return decl.Pos()
	}
	slices.SortStableFunc(decls, func(a, b ast.Decl) int {
		return cmp.Compare(position(a), position(b))
	})
}

// hasPositions reports whether every declaration of file lies within its bounds.
func hasPositions(file *ast.File) bool {
	if !file.FileStart.IsValid() {
		return false
	}
	valid := func(pos token.Pos) bool {
		return pos >= file.FileStart && (!file.FileEnd.IsValid() || pos < file.FileEnd)
	}
	for _, decl := range file.Decls {
		if gen, ok := decl.(*ast.GenDecl); ok {
			if gen.Tok == token.IMPORT {
				continue
			}
			if isValueOrType(gen.Tok) {
				for _, spec := range gen.Specs {
					if !valid(spec.Pos()) {
						return false
					}
				}
				continue
			}
		}
		if !valid(decl.Pos()) {
			return false
		}
	}
	return true
}

func valueOrTypeDecl(decl ast.Decl) (*ast.GenDecl, bool) {
	gen, ok := decl.(*ast.GenDecl)
	return gen, ok && isValueOrType(gen.Tok)
}

func isValueOrType(tok token.Token) bool {
	return tok == token.TYPE || tok == token.VAR || tok == token.CONST
}
