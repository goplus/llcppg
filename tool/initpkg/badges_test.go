// End-to-end through Init: the README change lands in the single main commit.

// newTemplateRepoWithReadme builds a template whose main branch carries a
// README with the given content (MODULE_NAME placeholder allowed). It mirrors
// newTemplateRepo but adds the README so the badge step has something to edit.
func newTemplateRepoWithReadme(t *testing.T, readme string) string {
	t.Helper()
	src := t.TempDir()
	runGit(t, src, "init", "-q", "-b", branchMain)

	writeTestFile(t, src, "go.mod", "module "+Placeholder+"\n\ngo 1.27.0\n")
	writeTestFile(t, src, "main.go", "package main\n")
	writeTestFile(t, src, "README.md", readme)
	runGit(t, src, "add", "-A")
	runGit(t, src, "commit", "-q", "-m", "template main")

	runGit(t, src, "checkout", "-q", "--orphan", branchC)
	runGit(t, src, "rm", "-rf", "-q", ".")
	writeTestFile(t, src, "c/go.mod", "module "+Placeholder+"\n\ngo 1.27.0\n")
	writeTestFile(t, src, "c/llcppg.cfg", `{"Name":"`+Placeholder+`"}`+"\n")
	runGit(t, src, "add", "-A")
	runGit(t, src, "commit", "-q", "-m", "template c")
	runGit(t, src, "checkout", "-q", branchMain)

	bare := filepath.Join(t.TempDir(), "template.git")
	cmd := exec.Command("git", "clone", "-q", "--bare", src, bare)
	cmd.Env = testEnv()
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("clone bare template: %v\n%s", err, out)
	}
	return "file://" + bare
}

func TestInit_AddsBadgesInMainCommit(t *testing.T) {
	tmpl := newTemplateRepoWithReadme(t, "# cjson\n\nGo bindings for the cJSON library.\n")
	cache := t.TempDir()
	target := newEmptyTarget(t)

	if _, _, err := runInit(t, target, "cjson", &Config{TemplateURL: tmpl, CacheDir: cache}); err != nil {
		t.Fatalf("Init: %v", err)
	}

	// The README on main carries the badges.
	content, ok := fileOnBranch(t, target, branchMain, "README.md")
	if !ok {
		t.Fatal("README.md missing on main after init")
	}
	if !strings.Contains(content, badgeMarker("cjson")) {
		t.Errorf("badges not added to the main README:\n%s", content)
	}
	if !strings.Contains(content, "# cjson\n\n[![GoDoc]") {
		t.Errorf("badges not placed right after the title:\n%s", content)
	}

	// Still exactly one commit on main: the README edit is part of it, not a
	// separate commit.
	if count := strings.TrimSpace(mustGit(t, target, "rev-list", "--count", branchMain)); count != "1" {
		t.Errorf("main has %s commits, want 1 (badge edit must share the main commit)", count)
	}
	// The working tree is clean: the badge edit was committed, not left staged.
	if status := strings.TrimSpace(mustGit(t, target, "status", "--porcelain")); status != "" {
		t.Errorf("working tree not clean after init:\n%s", status)
	}
}

func TestInit_InferredNameInBadges(t *testing.T) {
	tmpl := newTemplateRepoWithReadme(t, "# title\n\nText.\n")
	cache := t.TempDir()
	target := filepath.Join(t.TempDir(), "cjson")
	if err := os.MkdirAll(target, 0755); err != nil {
		t.Fatal(err)
	}
	runGit(t, target, "init", "-q", "-b", branchMain)

	if _, _, err := runInit(t, target, "", &Config{TemplateURL: tmpl, CacheDir: cache}); err != nil {
		t.Fatalf("Init with inferred module name: %v", err)
	}
	content, ok := fileOnBranch(t, target, branchMain, "README.md")
	if !ok {
		t.Fatal("README.md missing on main")
	}
	// The inferred name (the directory base, "cjson") fills the badges.
	if !strings.Contains(content, badgeMarker("cjson")) {
		t.Errorf("inferred module name not used in badges:\n%s", content)
	}
}

func TestInit_NoReadmeOnMainIsFine(t *testing.T) {
	// The default template helper has no README on main; init must still succeed
	// and leave no README behind.
	tmpl := newTemplateRepo(t)
	cache := t.TempDir()
	target := newEmptyTarget(t)

	_, stderr, err := runInit(t, target, "cjson", &Config{TemplateURL: tmpl, CacheDir: cache})
	if err != nil {
		t.Fatalf("Init without a template README: %v", err)
	}
	if strings.Contains(stderr, "badge") {
		t.Errorf("unexpected badge warning when there is no README: %q", stderr)
	}
	if _, ok := fileOnBranch(t, target, branchMain, "README.md"); ok {
		t.Error("a README.md was created where the template had none")
	}
}
