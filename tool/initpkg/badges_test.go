// fileOnDisk reads a file from dir's working tree and reports whether it exists.
func fileOnDisk(t *testing.T, dir, name string) (string, bool) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		return "", false
	}
	return string(data), true
}

// badgeBlock is the exact four-line block that must appear for module, joined
// with the given newline, used to assert on the inserted text.
func badgeBlock(module, nl string) string {
	return strings.Join(badgeLines(module), nl)
}

