// Unit tests for insertBadges: the pure text transform.

func TestInsertBadges_ATXTitle(t *testing.T) {
	in := "# cjson\n\nGo bindings for the cJSON library, generated by llcppg.\n"
	out, ok := insertBadges(in, "cjson")
	if !ok {
		t.Fatal("expected a title to be found")
	}
	want := "# cjson\n\n" + badgeBlock("cjson", "\n") + "\n\nGo bindings for the cJSON library, generated by llcppg.\n"
	if out != want {
		t.Errorf("insertBadges mismatch:\n got:\n%q\nwant:\n%q", out, want)
	}
}

