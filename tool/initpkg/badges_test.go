func TestInsertBadges_CRLF(t *testing.T) {
	in := "# cjson\r\n\r\nText.\r\n"
	out, ok := insertBadges(in, "cjson")
	if !ok {
		t.Fatal("expected a title to be found in a CRLF file")
	}
	want := "# cjson\r\n\r\n" + badgeBlock("cjson", "\r\n") + "\r\n\r\nText.\r\n"
	if out != want {
		t.Errorf("CRLF handling mismatch:\n got:\n%q\nwant:\n%q", out, want)
	}
	// No lone LF badge separators crept in.
	if strings.Contains(strings.ReplaceAll(out, "\r\n", ""), "\n") {
		t.Errorf("a lone LF leaked into a CRLF file:\n%q", out)
	}
}

