func TestInsertBadges_ModuleNameInEveryBadgeURL(t *testing.T) {
	out, ok := insertBadges("# zlib\n\nText.\n", "zlib")
	if !ok {
		t.Fatal("expected a title to be found")
	}
	// The module name must appear, with the fixed org name, in every URL of the
	// GoDoc and release badges: the badge image and link of each (four URLs).
	for _, want := range []string{
		"https://pkg.go.dev/badge/github.com/llarhub/zlib.svg",
		"https://pkg.go.dev/github.com/llarhub/zlib",
		"https://img.shields.io/github/v/tag/llarhub/zlib.svg?label=release",
		"https://github.com/llarhub/zlib/releases",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("expected URL %q in badges:\n%s", want, out)
		}
	}
	// The LLGo and XGo badges are fixed and carry no module name.
	if !strings.Contains(out, "https://github.com/xgo-dev/llgo") ||
		!strings.Contains(out, "https://github.com/goplus/xgo") {
		t.Errorf("fixed LLGo/XGo badge URLs missing:\n%s", out)
	}
}

