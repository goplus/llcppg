func TestInsertBadges_Level2BeforeLevel1(t *testing.T) {
	// A level-2 heading (## and --- underline) before any level-1 heading must be
	// ignored; the later level-1 heading wins.
	in := "## Usage\n\nsub\n---\n\n# cjson\n\nText.\n"
	out, ok := insertBadges(in, "cjson")
	if !ok {
		t.Fatal("expected the later level-1 heading to be used")
	}
	if !strings.Contains(out, "# cjson\n\n[![GoDoc]") {
		t.Errorf("badges not placed at the level-1 heading:\n%q", out)
	}
	// Nothing was inserted at the level-2 material.
	if strings.Contains(out, "## Usage\n\n[![GoDoc]") {
		t.Errorf("badges wrongly inserted at a level-2 heading:\n%q", out)
	}
}

