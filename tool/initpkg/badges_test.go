func TestAddReadmeBadges_AlreadyPresentNotAddedTwice(t *testing.T) {
	dir := t.TempDir()
	// A README that already carries the GoDoc badge for the module.
	orig := "# cjson\n\n" + badgeBlock("cjson", "\n") + "\n\nText.\n"
	writeTestFile(t, dir, "README.md", orig)

	var errOut strings.Builder
	addReadmeBadges(dir, "cjson", &errOut)

	got, _ := fileOnDisk(t, dir, "README.md")
	if got != orig {
		t.Errorf("README was modified although badges were already present:\n%q", got)
	}
	// Exactly one GoDoc badge, not two.
	if n := strings.Count(got, badgeMarker("cjson")); n != 1 {
		t.Errorf("GoDoc badge marker appears %d times, want 1", n)
	}
}

