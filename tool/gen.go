const (
	DbgFlagLoadSource = 1 << iota
	DbgFlagImport
	DbgFlagAll = DbgFlagLoadSource | DbgFlagImport
)

var (
	debugLoadSource bool
	debugImport     bool
)

func SetDebug(flags int) {
	debugLoadSource = (flags & DbgFlagLoadSource) != 0
	debugImport = (flags & DbgFlagImport) != 0
}

